$blogPlainContent = static function (string $content): string {
    $content = preg_replace('~</(?:p|h2|h3|li)>~i', "\n\n", $content);
    return trim(html_entity_decode(strip_tags((string)$content), ENT_QUOTES | ENT_HTML5, 'UTF-8'));
};

